CREATE TABLE IF NOT EXISTS schema_migrations (
  version VARCHAR(50) PRIMARY KEY,
  applied_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE room_type (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  max_guests SMALLINT NOT NULL,
  room_count SMALLINT NOT NULL,
  rate_low NUMERIC(8,2) NOT NULL,
  rate_mid NUMERIC(8,2) NOT NULL,
  rate_high NUMERIC(8,2) NOT NULL
);

CREATE TABLE room (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number SMALLINT NOT NULL UNIQUE,
  room_type_id INTEGER NOT NULL REFERENCES room_type (id)
);
-- PostgreSQL indekserer ikke fremmednøgler automatisk (det gjorde MySQL).
CREATE INDEX idx_room_room_type ON room (room_type_id);

CREATE TABLE guest (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name VARCHAR(100) NOT NULL,
  family_name VARCHAR(100) NOT NULL,
  country VARCHAR(100) NOT NULL
);
CREATE INDEX idx_guest_country ON guest (country);

CREATE TABLE booking (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_id INTEGER NOT NULL REFERENCES guest (id),
  room_id INTEGER NOT NULL REFERENCES room (id),
  check_in DATE NOT NULL,
  check_out DATE NOT NULL,
  nights SMALLINT NOT NULL,
  guests SMALLINT NOT NULL,
  season TEXT NOT NULL CHECK (season IN ('low', 'mid', 'high')),
  year SMALLINT NOT NULL,
  price NUMERIC(10,2) NOT NULL,
  price_is_manual BOOLEAN NOT NULL DEFAULT FALSE,
  satisfaction SMALLINT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  updated_at TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_booking_room_period ON booking (room_id, check_in, check_out);
CREATE INDEX idx_booking_year ON booking (year);
CREATE INDEX idx_booking_guest ON booking (guest_id);

CREATE TABLE drink (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  category TEXT NOT NULL CHECK (category IN ('Cocktail', 'Coffee')),
  unit_price NUMERIC(8,2) NOT NULL
);

CREATE TABLE drink_sale (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drink_id INTEGER NOT NULL REFERENCES drink (id),
  units INTEGER NOT NULL,
  unit_price NUMERIC(8,2) NOT NULL,
  sold_at TIMESTAMP NOT NULL,
  year SMALLINT NOT NULL,
  bartender VARCHAR(100) NOT NULL DEFAULT 'Helene Christine'
);
CREATE INDEX idx_drink_sale_year ON drink_sale (year);
CREATE INDEX idx_drink_sale_drink ON drink_sale (drink_id);
